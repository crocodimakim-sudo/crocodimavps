    p.add_argument("--штампы", dest="штампы", default=ПУТЬ_ШТАМПОВ, help="путь к штампы.json")
    a = p.parse_args(argv)
    if len(a.файлы) > 2:
        p.error("нужен один файл или два (было стало)")
    for s in (sys.stdout, sys.stderr):
        try:
            s.reconfigure(encoding="utf-8")
        except Exception:
            pass
    штампы = загрузить_штампы(a.штампы)
    результаты = []
    for путь in a.файлы:
        try:
            результаты.append(замерить(прочитать(путь), штампы))
        except OSError as e:
            print("Не удалось прочитать %s: %s" % (путь, e), file=sys.stderr)
            return 2
    if a.json:
        data = результаты[0] if len(результаты) == 1 else {"было": результаты[0], "стало": результаты[1]}
