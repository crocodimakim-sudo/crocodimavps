"""Локальный замер «похоже на нейросеть» (русский текст, .txt/.md).

ВАЖНО: это локальные эвристики; правила: pravila-proekta/03-stop-slova-neyroslop.md.
Скрипт не определяет авторство и не обещает
«незаметности для детекторов»: он показывает места, где текст похож на шаблон,
чтобы редактор переписал их руками.

Пять признаков, каждый 0-100 (больше = человечнее): РИТМ, КОНКРЕТИКА, ШТАМПЫ, СЛЕДЫ, ГОЛОС.
Итог = 60 % среднее + 40 % самый слабый признак.

Примеры:
  python -X utf8 detect_ai.py статья.md
  python -X utf8 detect_ai.py было.md стало.md     (сравнение)
  python -X utf8 detect_ai.py статья.md --json
"""
