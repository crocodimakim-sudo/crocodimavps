# Запуск: python -X utf8 test_tools.py
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import clean_text  # noqa: E402
import detect_ai  # noqa: E402

ошибки = []


def проверка(имя, условие, подробности=""):
    print(("ок      " if условие else "ПРОВАЛ  ") + имя + ((" | " + str(подробности)) if not условие else ""))
    if not условие:
        ошибки.append(имя)


# --- clean_text ---
грязный = "Привет​, мир­ — «ёлочки», „лапки“, а–б, ждём… ещё тут﻿‮\U000E0041."
чистый, удалено = clean_text.очистить(грязный)
проверка("очистка удаляет U+200B", "​" not in чистый)
проверка("очистка удаляет мягкий перенос U+00AD", "­" not in чистый)
проверка("очистка удаляет FEFF, bidi и теги", not any(c in чистый for c in "﻿‮\U000E0041"))
проверка("очистка сохраняет длинное и короткое тире", "—" in чистый and "–" in чистый)
проверка("очистка сохраняет «ёлочки», „лапки“ и многоточие", "«ёлочки»" in чистый and "„лапки“" in чистый and "…" in чистый)
проверка("очистка сохраняет U+00A0 и U+202F", " " in чистый and " " in чистый)
проверка("счётчик удалённого верный", sum(удалено.values()) == 5, удалено)
замена, _ = clean_text.очистить(грязный, nbsp_to_space=True)
проверка("--nbsp-to-space заменяет неразрывные пробелы", " " not in замена and " " not in замена)
проверка("--check: код 1 на грязном, 0 на чистом",
         bool(clean_text.найти_невидимые(грязный)) and not clean_text.найти_невидимые(чистый))

# --- detect_ai ---
штампы = detect_ai.загрузить_штампы()
проверка("штампы.json: не меньше 60 записей", len(штампы) >= 60, len(штампы))

шаблон = (
    "Важно понимать, что фасадные материалы играют ключевую роль в современном строительстве.\n\n"
    "Стоит отметить, что комплексный подход обеспечивает надёжность и высокое качество решения.\n\n"
    "Таким образом, оптимальное решение позволяет эффективно реализовать широкий спектр задач.\n\n"
    "Данный материал является неотъемлемой частью инновационных систем отделки здания.\n\n"
    "Это не просто плита, это уникальное решение для современного объекта строительства.\n\n"
    "В заключение хочется подчеркнуть значимость правильного выбора фасадного материала.\n"
)
конкретный = (
    "Плита материала весит 14 кг на квадратный метр. Это значит, что подсистему можно ставить на кирпичную стену "
    "без усиления.\n\n"
    "Толщина 8 мм. Расстояние между направляющими не больше 600 мм по ГОСТ 31251, иначе листы дадут волну. "
    "На объекте в Мытищах мы видели это на трёх фасадах из десяти, и все три монтировали без разметки.\n\n"
    "Крепёж берите из нержавейки: сталь с цинком ржавеет за два сезона.\n\n"
    "Сколько стоит? От 2 400 ₽ за квадратный метр материала, без работ. Работы считает бригада отдельно, "
    "и цифра зависит от высоты здания и числа проёмов, поэтому смету лучше просить по обмеру.\n\n"
    "Зимой клеевой состав держится плохо при температуре ниже +5 °C, поэтому мы ставим на механический крепёж.\n"
)
р_шаблон = detect_ai.замерить(шаблон, штампы)
р_конкр = detect_ai.замерить(конкретный, штампы)
проверка("шаблонный текст получает итог ниже конкретного", р_шаблон["итог"] < р_конкр["итог"],
         (р_шаблон["итог"], р_конкр["итог"]))
проверка("шаблонный текст не получает ПРОШЁЛ", р_шаблон["вердикт"] != "ПРОШЁЛ", р_шаблон["вердикт"])
проверка("конкретный текст получает ПРОШЁЛ", р_конкр["вердикт"] == "ПРОШЁЛ", (р_конкр["вердикт"], р_конкр["признаки"]))
проверка("шаблонный текст: штампы найдены", any(f["признак"] == "ШТАМПЫ" for f in р_шаблон["флаги"]))

не_а = detect_ai.замерить("Нужна не скорость, а системность. Мы делаем иначе.", штампы)
проверка("флаг «не X, а Y» находится", any("не X, а Y" in f["метка"] for f in не_а["флаги"]), не_а["флаги"])
не_просто = detect_ai.замерить("Это не просто сервис, это экосистема.", штампы)
проверка("флаг «это не просто X, это Y» находится", len(не_просто["флаги"]) >= 1, не_просто["флаги"])
вопрос = detect_ai.замерить("Описание.\n\nРезультат?\n\nМы сделали фасад.\n", штампы)
проверка("риторический вопрос-строка флагуется", any("вопрос" in f["метка"] for f in вопрос["флаги"]))
невид = detect_ai.замерить("Текст с​ невидимым символом.", штампы)
проверка("невидимый символ снижает СЛЕДЫ", невид["признаки"]["СЛЕДЫ"]["балл"] < 100)

print()
if ошибки:
    print("ПРОВАЛЕНО проверок: %d" % len(ошибки))
    sys.exit(1)
print("Все проверки прошли.")
